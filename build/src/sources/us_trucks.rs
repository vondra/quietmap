/// The US state (FIPS) at a point; 0 outside the states.
pub(crate) fn us_state(lat: f64, lon: f64) -> u8 {
    let row = ((STATE_NORTH - lat) / STATE_STEP).floor();
    let column = ((lon - STATE_WEST) / STATE_STEP).floor();
    if !(0.0..(STATE_ROW_STARTS.len() - 1) as f64).contains(&row) || column < 0.0 {
        return 0;
    }
    let row = row as usize;
    let runs =
        &STATE_RUNS[usize::from(STATE_ROW_STARTS[row])..usize::from(STATE_ROW_STARTS[row + 1])];
    let column = column as usize;
    let index = runs.partition_point(|&(end, _)| usize::from(end) <= column);
    runs.get(index).map_or(0, |&(_, state)| state)
}

/// The road group of a dev4 class: motorways and their links the Interstates, trunk to secondary
/// roads and their links the other arterials, the rest the other roads.
fn road_group(class_index: usize) -> u8 {
    match class_index {
        0 | 10 => 0,
        1..=3 | 11 | 12 => 1,
        _ => 2,
    }
}

/// The light, medium, heavy and motorcycle shares of a US road's traffic at a point (built-up 1
/// rural, 2 urban, unknown the mean of both); `None` outside the states.
pub(crate) fn us_vehicle_shares(
    lat: f64,
    lon: f64,
    class_index: usize,
    built_up: u8,
) -> Option<[f64; 4]> {
    let state = us_state(lat, lon);
    let group = road_group(class_index);
    let &(_, _, [rural, urban]) = US_VEHICLE_SHARES
        .binary_search_by_key(&(state, group), |row| (row.0, row.1))
        .ok()
        .map(|index| &US_VEHICLE_SHARES[index])?;
    Some(match built_up {
        1 => rural,
        2 => urban,
        _ => std::array::from_fn(|k| 0.5 * (rural[k] + urban[k])),
    })
}

