#!/usr/bin/env node
//! Generate engine/noise-compute/src/country_speed_defaults_generated.rs from a
//! local scripts/legal-default-speeds.json dump (osm-legal-default-speeds —
//! machine-readable parse of the OSM wiki "Default speed limits" legal tables).
//! The dump is gitignored; the generated Rust/JSON tables are the committed truth.
//!
//! Per country we keep exactly four legal buckets (km/h, 0 = country has no value):
//!   urban     ← rule named "urban", else a name ending "restricted road" (GB's legal
//!               urban concept: street-lit roads default to 30 mph)
//!   rural     ← rule named "rural", else the UNNAMED rule (the dataset's fallback =
//!               rural single carriageway in every jurisdiction checked)
//!   motorway / motorroad ← resolved through the dataset's roadTypesByName FILTERS,
//!               not rule names — localized rules ("Italy: Autostrada" = {motorway})
//!               would be invisible to name matching (/gg Codex 2026-07-03). Among
//!               non-{urban} candidates the LAST rule wins (dataset order = most
//!               specific last). Value = maxspeed, else maxspeed:advisory — Germany's
//!               Autobahn has ONLY the advisory 130, which is also what our
//!               derestricted model uses (BASt-backed, SPEC.md).
//! Value parse: "50" → 50 · "60 mph" → 97 · "-" (no limit) → 130 (the engine's
//! DERESTRICTED_SPEED_KMH cap) · "walk"/other words → bucket stays 0.
//! Countries with all four buckets 0 (e.g. US — state law, no national default) are
//! omitted: the engine then falls back to the legacy world default table.
//!
//! To refresh:
//!   curl -fsSL https://westnordost.github.io/osm-legal-default-speeds/legal_default_speeds.json \
//!     -o scripts/legal-default-speeds.json
//!   node scripts/gen-country-speed-defaults-rs.mjs
//!   # commit only the generated Rust + pipeline JSON (not the dump)

import { readFileSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const SRC = resolve(ROOT, 'scripts/legal-default-speeds.json')
const OUT = resolve(ROOT, 'engine/noise-compute/src/country_speed_defaults_generated.rs')

const kmh = (v) => {
  if (v == null) return 0
  const s = String(v).trim()
  if (s === '-') return 130 // no legal limit → engine derestricted cap (BASt-backed, SPEC.md)
  const m = s.match(/^(\d+(?:\.\d+)?)(\s*mph)?$/)
  if (!m) return 0 // "walk" and friends — not a numeric limit
  return Math.round(parseFloat(m[1]) * (m[2] ? 1.609344 : 1))
}

const data = JSON.parse(readFileSync(SRC, 'utf8'))
const byCountry = data.speedLimitsByCountryCode

const roadTypes = data.roadTypesByName
const filterOf = (r) => roadTypes[r.name ?? '']?.filter ?? ''
// A rule is a <kind> rule when its road-type filter references the {kind} placeholder or
// lists kind as an exact highway-class token. Token match ONLY: the generic 'rural' rule's
// filter mentions motorway/motorroad inside source:maxspeed REGEXES (tag names, not road
// classes) — a substring test wrongly claimed every rural rule for both buckets.
// {urban}-scoped variants are excluded — the buckets carry the RURAL/legal-mainline value.
const isKind = (r, kind) => {
  const f = filterOf(r)
  if (f.includes('{urban}')) return false
  if (f.includes(`{${kind}}`)) return true
  const m = f.match(/highway~([\w|]+)/)
  return !!m && m[1].split('|').includes(kind)
}
const rows = []
for (const [code, rules] of Object.entries(byCountry)) {
  if (!/^[A-Z]{2}$/.test(code)) continue // subdivisions (US-CA…) — admin gives country only
  const named = (pred) => rules.find((r) => pred(r.name ?? ''))
  const speedOf = (r) => kmh(r?.tags?.maxspeed ?? r?.tags?.['maxspeed:advisory'])
  const lastKind = (kind) => rules.filter((r) => isKind(r, kind)).map(speedOf).filter(Boolean).at(-1) || 0
  const urban = speedOf(named((n) => n === 'urban')) || speedOf(named((n) => n.endsWith('restricted road')))
  const rural = speedOf(named((n) => n === 'rural')) || speedOf(rules.find((r) => !r.name))
  const motorway = lastKind('motorway')
  const motorroad = lastKind('motorroad')
  if (urban || rural || motorway || motorroad) rows.push([code, urban, rural, motorway, motorroad])
}
rows.sort((a, b) => a[0].localeCompare(b[0]))

const meta = data.meta ? ` (dataset ${JSON.stringify(data.meta).slice(0, 120)})` : ''
const body = rows.map(([c, u, r, m, mr]) =>
  `    (b"${c}", [${u}, ${r}, ${m}, ${mr}]),`).join('\n')
writeFileSync(OUT, `//! Per-country LEGAL default speeds (km/h) for roads with no OSM maxspeed tag.
//! Generated by scripts/gen-country-speed-defaults-rs.mjs from
//! scripts/legal-default-speeds.json — the osm-legal-default-speeds project's
//! machine-readable parse of the OSM wiki "Default speed limits" tables${meta}.
//! Buckets: [urban, rural, motorway, motorroad]; 0 = no legal value → the caller
//! falls back to the legacy world table (defaults.rs::resolve_speed_default).
//! Do not edit by hand — regenerate (header of the generator has the recipe).

/// [urban, rural, motorway, motorroad] km/h; 0 = absent. Sorted by ISO code
/// for binary search.
pub const COUNTRY_SPEEDS: &[(&[u8; 2], [u8; 4])] = &[
${body}
];
`)
// TS/JSON companion of the SAME distilled table (the gen-sources-rs dual-output
// pattern): pipeline consumers (R7 taper) read this instead of hand-copying
// numbers that would silently drift on the next JSON refresh.
const TS_OUT = resolve(ROOT, 'pipeline/lib/country-speed-defaults.generated.json')
writeFileSync(
  TS_OUT,
  JSON.stringify(
    { _doc: 'Generated by scripts/gen-country-speed-defaults-rs.mjs — [urban, rural, motorway, motorroad] km/h, 0 = absent. Do not edit.',
      ...Object.fromEntries(rows.map(([c, u, r, m, mr]) => [c, [u, r, m, mr]])) },
    null, 1,
  ) + '\n',
)
console.log(`gen-country-speed-defaults: ${rows.length} countries → ${OUT} + ${TS_OUT}`)
const show = (c) => { const r = rows.find((x) => x[0] === c); console.log(`  ${c}: urban=${r?.[1]} rural=${r?.[2]} motorway=${r?.[3]} motorroad=${r?.[4]}`) }
;['GB', 'CZ', 'DE', 'FR', 'PL'].forEach(show)
