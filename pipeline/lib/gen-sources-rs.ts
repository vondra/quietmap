const TS_OUTPUT_PATH = resolve(__dirname, 'source-ids.generated.ts')

/** Convert a source `key` into a SCREAMING_SNAKE TS / Rust identifier:
 *  `'cz-rsd-scitani'` → `'CZ_RSD_SCITANI'`. */
function keyToConstName(key: string): string {
  return key
    .replace(/[^A-Za-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '')
    .toUpperCase()
}

const PROVENANCE_TO_RUST: Record<Provenance, string> = {
  'city-measured': 'Provenance::CityMeasured',
  'national-measured': 'Provenance::NationalMeasured',
  'continental-measured': 'Provenance::ContinentalMeasured',
  'global-measured': 'Provenance::GlobalMeasured',
  'national-proxy': 'Provenance::NationalProxy',
  'heuristic': 'Provenance::Heuristic',
  'baseline': 'Provenance::Baseline',
  'none': 'Provenance::None',
}

/** Serialise a string for a Rust string literal — JSON escaping matches Rust. */
function rustStr(s: string): string {
  return JSON.stringify(s)
}

function rustOptStr(s: string | null): string {
  return s === null ? 'None' : `Some(${rustStr(s)})`
}

function rustOptU16(n: number | null): string {
  return n === null ? 'None' : `Some(${n})`
}

