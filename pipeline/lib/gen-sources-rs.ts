/**
 * Generate `engine/noise-compute/src/sources.rs` from `pipeline/lib/sources.ts`.
 *
 * Single source of truth for dataset metadata is the TypeScript registry.
 * This script produces the Rust mirror that the engine compiles in — no
 * `build.rs` → `npx tsx` chain (plan v5 /gg W: keep Rust builds pure Rust).
 *
 * Workflow: edit `sources.ts` → run `npm run gen:sources` (from pipeline/)
 * → commit both files together. Pre-commit hook may check the two stay in
 * sync.
 *
 * Usage:
 *   cd pipeline && npx tsx lib/gen-sources-rs.ts
 *   # or
 *   cd pipeline && npm run gen:sources
 */

